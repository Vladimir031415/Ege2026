a = "hh" + "01"*500 + "hh"
a = list(a)
t = [[["1", "R", "1"], ["0", "R", "1"], ["0", "R", "1"]],
     [["2", "R", "2"], ["1", "R", "2"], ["1", "R", "2"]],
     [["3", "S", "0"], ["3", "R", "0"], ["3", "R", "0"]]]


def f(q, z):
    if z == "h": k = 0
    if z == "0": k = 1
    if z == "1": k = 2
    return t[q][k]

n = 1
q = 0
while f(q, a[n])[1]!= "S":
    h = f(q, a[n])
    a[n] = h[0]
    q = int(h[2])
    if h[1] == "L":
        n = n - 1
    elif h[1] == "R":
        n = n + 1
a = "".join(a)
print(a)